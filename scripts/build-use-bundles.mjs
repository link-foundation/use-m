#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { transform } from 'esbuild'

export const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export const USE_SOURCE_FRAGMENTS = [
  'src/use/core.js',
  'src/use/resolvers.js',
  'src/use/coordination.js',
  'src/use/runtime.js',
]

const BUNDLE_NAMES = ['use.js', 'use.cjs', 'use.mjs']
export const USE_BUNDLE_PATHS = [
  ...BUNDLE_NAMES,
  ...BUNDLE_NAMES.map(name => `src/${name}`),
]

const exportedNames = [
  'parseModuleSpecifier',
  'resolvers',
  'makeUse',
  'baseUse',
  'loadWithFallback',
  'networkResolverChain',
  'denoResolverChain',
  'use',
]

const variants = {
  'use.mjs': {
    defaultScriptPath: `  if (!scriptPath) {
    scriptPath = import.meta.url;
  }`,
    footer: `export { ${exportedNames.join(', ')} };`,
  },
  'use.cjs': {
    defaultScriptPath: '',
    footer: `module.exports = {
${exportedNames.map(name => `  ${name},`).join('\n')}
};`,
  },
  'use.js': {
    defaultScriptPath: `  if (!scriptPath && typeof window === 'undefined' && typeof require === 'undefined') {
    const stack = new Error().stack || '';
    const regex = /at[^:\\/]+(file:\\/\\/)?(?<path>(\\/|(?<=\\W)\\w:)[^):]+):\\d+:\\d+/;
    const match = stack.match(regex);
    if (match?.groups?.path) {
      const { pathToFileURL } = await import('node:url');
      scriptPath = pathToFileURL(match.groups.path).href;
    }
  }`,
    footer: `${exportedNames.map(name => `makeUse.${name} = ${name};`).join('\n')}

makeUse`,
  },
}

const rootHeader = (basename) => [
  `// AUTO-GENERATED — do not edit ${basename} directly.`,
  '// This readable, single-file distribution bundle is built deterministically',
  '// from the smaller source fragments in src/use/. Run `npm run build` after',
  '// editing those fragments. The root file remains available for historical',
  `// CDN URLs such as https://unpkg.com/use-m/${basename}.`,
].join('\n')

const compatibilityHeader = (basename) => [
  `// AUTO-GENERATED compact compatibility bundle for /src/${basename}.`,
  '// Edit src/use/* and run `npm run build`; do not edit this file directly.',
].join('\n')

const replaceExactlyOnce = (source, marker, replacement) => {
  const parts = source.split(marker)
  if (parts.length !== 2) {
    throw new Error(`Expected exactly one '${marker}' marker, found ${parts.length - 1}.`)
  }
  return `${parts[0]}${replacement}${parts[1]}`
}

export async function readUseSource() {
  const fragments = await Promise.all(
    USE_SOURCE_FRAGMENTS.map(relativePath => readFile(path.join(repoRoot, relativePath), 'utf8'))
  )
  return fragments.map(fragment => fragment.trimEnd()).join('\n\n')
}

export async function renderReadableBundle(basename, source = undefined) {
  const variant = variants[basename]
  if (!variant) throw new Error(`Unknown use-m bundle '${basename}'.`)
  const sharedSource = source ?? await readUseSource()
  const body = replaceExactlyOnce(
    sharedSource,
    '  // @use-m-default-script-path',
    variant.defaultScriptPath
  )
  return `${rootHeader(basename)}\n${body.trimEnd()}\n\n${variant.footer}\n`
}

export async function renderCompatibilityBundle(basename, readableBundle) {
  const { code } = await transform(readableBundle, {
    charset: 'utf8',
    legalComments: 'none',
    loader: 'js',
    minifyIdentifiers: false,
    minifySyntax: false,
    minifyWhitespace: true,
    // Preserve current JavaScript semantics (notably dynamic import attributes)
    // while compacting whitespace. These bundles are not transpilation output.
    target: 'esnext',
  })
  return `${compatibilityHeader(basename)}\n${code.trim()}\n`
}

export async function buildUseBundles() {
  const source = await readUseSource()
  const bundles = new Map()
  for (const basename of BUNDLE_NAMES) {
    const readable = await renderReadableBundle(basename, source)
    bundles.set(basename, readable)
    bundles.set(`src/${basename}`, await renderCompatibilityBundle(basename, readable))
  }
  return bundles
}

export async function writeUseBundles() {
  const bundles = await buildUseBundles()
  for (const [relativePath, contents] of bundles) {
    await writeFile(path.join(repoRoot, relativePath), contents)
    // Keep stdout machine-readable for callers such as `npm pack --json`.
    console.error(`built ${relativePath} (${contents.length} bytes)`)
  }
}

const invokedDirectly =
  typeof process !== 'undefined' &&
  Array.isArray(process.argv) &&
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (invokedDirectly) {
  writeUseBundles().catch(error => {
    console.error(error)
    process.exitCode = 1
  })
}
